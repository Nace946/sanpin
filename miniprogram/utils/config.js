// 调用与缓存策略集中配置（改完保存即可，无需改动其他文件）

/**
 * DIRECT_READ：前台列表是否「直连数据库读取」，跳过云函数
 *
 * 效果：
 *   false（默认）→ 每次缓存失效后 = 1 次云函数调用
 *   true         → 0 次云函数调用，只消耗「数据库读」额度（额度约 7 倍于调用次数）
 *
 * 打开前必须先在云开发控制台完成一步：
 *   数据库 → infos 集合 → 权限设置 → 改为「所有用户可读，仅创建者可写」
 *   （内容本来就是公开信息，放开读权限不额外暴露敏感数据；写权限仍限死，只能走云函数）
 *
 * 未改权限就打开也不会白屏：代码会自动回退云函数读取，并在控制台打印警告。
 */
const DIRECT_READ = false

/**
 * LIST_CACHE_TTL：列表缓存有效期（毫秒）
 *
 * 1 小时的含义：首次拉取后写进本机缓存，1 小时内（含退出小程序再进）都直接读缓存，
 * 不再请求数据库；超过 1 小时才重新拉取并覆盖缓存。
 *
 * 取舍：TTL 越长越省调用，但管理员新发布/下架的信息在别人手机上越晚可见。
 *   - 追求"发布即见"：改成 5 * 60 * 1000（5 分钟）
 *   - 追求省额度（当前）：60 * 60 * 1000（1 小时）
 */
const LIST_CACHE_TTL = 60 * 60 * 1000

/**
 * DETAIL_CACHE_TTL：详情页缓存有效期（毫秒）
 *
 * 详情页每真实请求一次，云函数就会把该条信息的 views +1。缓存 10 分钟的效果：
 *   - 10 分钟内重复进入同一条（含退出小程序再进）直接读缓存，不请求云函数，浏览量不加
 *   - 顺带挡住同一设备「点进去 → 返回 → 再点进去」反复刷浏览量
 *   - 代价：管理员改完这条内容，用户手机上最长 10 分钟才看到新版本（清缓存或换条再进可绕过）
 *
 * 想更实时就调小（5 分钟），想更省调用就调大，但浏览量会显得更"虚低"。
 */
const DETAIL_CACHE_TTL = 10 * 60 * 1000

/**
 * BANNER_CACHE_TTL：轮播图单独请求时的缓存有效期（毫秒）
 *
 * 注：首页现在走 homeMeta 一次拿「公告 + 轮播图」，实际生效的是下面的
 * HOME_CACHE_MAX_TTL；本常量仅在需要单独拉轮播图的场景保留。
 */
const BANNER_CACHE_TTL = 60 * 60 * 1000

/**
 * HOME_CACHE_MAX_TTL：首页「公告 + 轮播图」合并请求的缓存上限（毫秒）
 *
 * 首页首屏元数据走 adminAction 的 homeMeta，一次拿回公告与轮播图。
 * 缓存有效期取「距下一个公告刷新点」与「本上限」中的较小值：
 *   - 公告：沿用 NOTICE_REFRESH_HOURS（8:00 / 17:00）的节奏
 *   - 轮播图：管理员改完后，别人手机上最多等这么久就生效
 *
 * 2 小时是折中：既不把公告刷成每小时一次（那会白花调用），
 * 又不会让轮播图改完半天看不见。想让轮播图更快生效就调小。
 */
const HOME_CACHE_MAX_TTL = 2 * 60 * 60 * 1000

/**
 * NOTICE_REFRESH_HOURS：首页公告的每日刷新时间点（24 小时制，升序）
 *
 * 公告缓存不是固定 TTL，而是「到下一个刷新点为止」：
 *   7:30 打开 → 缓存 30 分钟；10:00 打开 → 缓存到 17:00；18:00 打开 → 缓存到次日 8:00
 * 效果是每天只在 8:00 与 17:00 各真正调用一次云函数，其余时间全读本地缓存。
 *
 * 想让公告更实时可以加时段，例如 [8, 12, 17]（每天三次）。
 */
const NOTICE_REFRESH_HOURS = [8, 17]

/**
 * PERSIST_CACHE：是否把缓存写入 Storage（冷启动复用）
 * 关闭后仅在本次运行内有效，退出小程序即失效——省额度的效果会大打折扣，建议保持开启。
 */
const PERSIST_CACHE = true

